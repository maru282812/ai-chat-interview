-- 116_store_terms_fix_appendix_version.sql
-- 会員利用規約（店舗向け）の**附則に残っていた**版表記を正式版に直す。
--
-- 背景:
--   115 で冒頭の draft 注記・URL・サービス名表記を是正したが、本文末尾の附則に
--     「- 版: 1.0-draft（弁護士確認前の案）」
--   という別の行が残っていた（105 の投入時から本文に埋め込まれていたもので、
--   冒頭注記とは文字列が違うため 115 の replace に掛からなかった）。
--   適用後の確認クエリで検出したので、同じ版のまま本文だけ直す。
--
-- 新バージョンを切らない理由は 115 と同じ（表記の修正で権利義務の変更なし・同意者ゼロ）。
--
-- 冪等: 旧表記を含む行だけを対象にする。適用済みなら 0 行更新で no-op。
-- 注意: 105 の本文は LF。

BEGIN;

UPDATE document_versions
SET content = replace(
                content,
                E'- 版: 1.0-draft（弁護士確認前の案）',
                E'- 版: 1.0'
              )
WHERE document_id = 'd1000000-0000-0000-0000-000000000001'::UUID
  AND content LIKE '%1.0-draft（弁護士確認前の案）%';

COMMIT;
